/// The deal in effect: "interleave" (e % W == rank, the default), "contig" (e / (ne/W)) or, TP-I #6,
/// "freq" (a per-layer frequency-balanced deal from the committed table, see `freq_deal`).
/// SPMD-relevant (it fixes each rank's expert GROUPING, hence the partial sums): `--ep-deal`
/// interleave|contig|freq is a registry option (CLI-1: the GB10_TP_EP_DEAL env override merged into
/// it); the head's value rides TpConfig (exl3_ep_deal + the option registry) to the node.
pub fn ep_deal_kind() -> String {
    if let Ok(v) = crate::opts::var(crate::opt!("ep-deal")) {
        match v.trim() {
            "freq" => return "freq".to_string(),
            "interleave" => return "interleave".to_string(),
            "contig" => return "contig".to_string(),
            _ => {}
        }
    }
    crate::tp::tp_config().map(|c| c.exl3_ep_deal.clone()).filter(|s| !s.is_empty())
        .unwrap_or_else(|| "interleave".to_string())
}

pub fn ep_owner(e: usize, ne: usize, world: usize, kind: &str) -> usize {
    match kind {
        "contig" => e / (ne / world).max(1),
        _ => e % world,
    }
}

/// TP-I #6: the committed frequency-balanced deal (data/ep_deal/*.json, regenerated by
/// scripts/ep_deal/derive_deal.py from --tp-ep-hist histograms). Per trunk layer, the experts
/// RANK 0 holds (exactly ne/2; rank 1 holds the complement), so the per-rank expert COUNT and
/// weight bytes are those of the static deals. World 2 only.
const FREQ_DEAL_JSON: &str = include_str!("../../data/ep_deal/qwen38_flash_next_tp2.json");

fn freq_deal() -> Result<&'static Vec<Vec<usize>>> {
    static T: std::sync::OnceLock<std::result::Result<Vec<Vec<usize>>, String>> = std::sync::OnceLock::new();
    T.get_or_init(|| {
        // --tp-ep-deal-file=<path> (diagnostic, rides the env snapshot; the file must exist on every rank's box):
        // an alternative deal table instead of the committed one
        let txt = match crate::opts::var(crate::opt!("tp-ep-deal-file")) {
            Ok(p) if !p.is_empty() => std::fs::read_to_string(&p).map_err(|e| format!("--tp-ep-deal-file {p}: {e}"))?,
            _ => FREQ_DEAL_JSON.to_string(),
        };
        let v: serde_json::Value = serde_json::from_str(&txt).map_err(|e| format!("deal table JSON: {e}"))?;
        let rows = v["rank0"].as_array().ok_or("deal table: no rank0 array")?;
        rows.iter().map(|r| r.as_array().ok_or("deal table: row not an array".to_string())
                .and_then(|a| a.iter().map(|x| x.as_u64().map(|u| u as usize).ok_or("deal table: bad id".to_string())).collect()))
            .collect()
    }).as_ref().map_err(|e| anyhow::anyhow!("{e}"))
}

/// Owner rank of every expert of trunk layer `layer` under the deal in effect.
pub fn ep_layer_owners(ne: usize, world: usize, layer: usize) -> Result<Vec<usize>> {
    let kind = ep_deal_kind();
    if kind != "freq" { return Ok((0..ne).map(|e| ep_owner(e, ne, world, &kind)).collect()); }
    anyhow::ensure!(world == 2, "--ep-deal=freq: the committed table is a world-2 deal (world {world})");
    let t = freq_deal()?;
    let r0 = t.get(layer).with_context(|| format!("--ep-deal=freq: the table has {} layers, no layer {layer} \
                                                   (a different model? regenerate it with scripts/ep_deal/)", t.len()))?;
    let mut own = vec![1usize; ne];
    for &e in r0 {
        anyhow::ensure!(e < ne, "--ep-deal=freq: layer {layer} names expert {e} >= ne {ne} (a different model?)");
        own[e] = 0;
    }
    anyhow::ensure!(r0.len() == ne / 2 && own.iter().filter(|&&o| o == 0).count() == ne / 2,
        "--ep-deal=freq: layer {layer} gives rank 0 {} distinct experts, expected ne/2 = {}", r0.len(), ne / 2);
    Ok(own)
}

/// This rank's routed experts of trunk layer `layer` in LOCAL stacked order (ascending global id).
pub fn ep_local_experts(ne: usize, rank: usize, world: usize, layer: usize) -> Result<Vec<usize>> {
    let own = ep_layer_owners(ne, world, layer)?;
    Ok((0..ne).filter(|&e| own[e] == rank).collect())
}

/// TP-I #8: --tp-ks-target=<blocks> — the resident-block target the split-K count of every
/// TP-SLICED dense quad (column / row slices of the trunk) is derived from, instead of the TP=1
/// heuristic's 200 (chain_ks), capped at TP_KS_MAX splits (every workspace is sized for it). Unset
/// / 0 = chain_ks, bit for bit. A different ks changes the fp32 split-K combine's grouping, so a
/// value that moves a shape's ks is output-changing (diagnostic / opt-in). Rides the env snapshot.
pub const TP_KS_MAX: u32 = 16;
pub fn tp_ks_target() -> Option<u32> {
    static T: std::sync::OnceLock<Option<u32>> = std::sync::OnceLock::new();
    *T.get_or_init(|| crate::opts::var(crate::opt!("tp-ks-target")).ok().and_then(|v| v.trim().parse::<u32>().ok()).filter(|&t| t > 0))
}
/// Workspace sizing: the largest split count a TP-sliced quad can take (0 when the knob is unset).
pub fn tp_ks_cap() -> u32 { if tp_ks_target().is_some() { TP_KS_MAX } else { 0 } }
pub fn tp_chain_ks(k: i32, n: i32) -> u32 {
    match tp_ks_target() {
        None => chain_ks(k, n),
        Some(t) => {
            let kb = (k.max(0) as u32) / 16;
            let mut ks = chain_ks_target(k, n, t).min(TP_KS_MAX);
            while ks > 1 && kb % ks != 0 { ks -= 1; }
            ks
        }
    }
}

/// ShardSpec::Experts of one MoE layer: global expert -> local stacked index (-1 = remote).
pub struct EpShard {
    pub lut: CudaSlice<i32>,
    pub rank: usize,
    pub world: usize,
    pub n_local: usize,
    /// TP-B: the layer's shared expert is intermediate-sharded (384 | 256): every rank adds its own
    /// sgv * partial in the EP combine (false = TP-A's replicated shared expert, rank 0 adds it).
    pub shared_split: bool,
}

impl EpShard {
    /// Load-time shape asserts (design §1.3: "the boot fails on a mismatch"): the deal covers
    /// every expert exactly once across ranks, the rank holds exactly ne/W of them, and every
    /// stacked table has exactly n_local experts' worth of words.
    #[allow(clippy::too_many_arguments)]
    pub fn new(dev: &Arc<CudaDevice>, ne: usize, rank: usize, world: usize, local: &[usize], tag: &str,
               gu_len: usize, d_len: usize, suh_gu_len: usize, svh_gu_len: usize, suh_d_len: usize,
               svh_d_len: usize, gu_words: u64, d_words: u64, h: usize, mi: usize) -> Result<Self> {
        anyhow::ensure!(world >= 2 && rank < world && ne % world == 0,
            "EP shard @{tag}: bad geometry ne={ne} rank={rank} world={world}");
        let kind = ep_deal_kind();
        let li: usize = tag.strip_prefix('L').and_then(|v| v.parse().ok()).unwrap_or(usize::MAX);
        let own = ep_layer_owners(ne, world, li)?;
        let mut seen = vec![0u8; ne];
        for r in 0..world {
            for e in (0..ne).filter(|&e| own[e] == r) { seen[e] += 1; }
        }
        anyhow::ensure!(seen.iter().all(|&c| c == 1), "EP shard @{tag}: deal '{kind}' does not cover every expert exactly once");
        let n = local.len();
        anyhow::ensure!(n == ne / world, "EP shard @{tag}: rank {rank} holds {n} experts, expected ne/W = {}", ne / world);
        let want = [
            ("gate|up trellis words", gu_len, n * gu_words as usize),
            ("down trellis words", d_len, n * d_words as usize),
            ("suh_gu", suh_gu_len, n * h),
            ("svh_gu", svh_gu_len, n * 2 * mi),
            ("suh_d", suh_d_len, n * mi),
            ("svh_d", svh_d_len, n * h),
        ];
        for (what, got, exp) in want {
            anyhow::ensure!(got == exp, "EP shard @{tag}: {what} = {got}, expected {exp} ({n} local experts) — refusing to boot");
        }
        let mut lut = vec![-1i32; ne];
        for (li, &e) in local.iter().enumerate() { lut[e] = li as i32; }
        Ok(EpShard { lut: dev.htod_sync_copy(&lut)?, rank, world, n_local: n, shared_split: false })
    }
}

