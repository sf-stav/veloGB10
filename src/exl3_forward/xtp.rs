/// TP-H2 — `--tp-vp-sampled <on|off>` (a CLI flag, no env): the vocab-parallel lm_head for the rows the
/// TP-H #4 greedy tail refuses (sampled / penalized / ratio-rule plain steps and verify rows). Each rank
/// runs the lm_head GEMM on its OWN 124160-column shard (bitwise the replicated head's columns), the
/// shard rows are ALL-GATHERED into the full logits rows through the decode doorbell
/// (xq_vp_gather_k1 / xq_vp_gather_k2, <= 4 rows per 1 MiB epoch), and the UNCHANGED penalty / argmax /
/// sampler kernels run on the reassembled rows — bitwise the replicated head's buffer by construction.
/// Needs the TP-H #4 shard (--tp-vp-head on, world 2). The head resolves it and ships the code in
/// TpConfig.exl3_vp_sampled (v21); the node installs the head's value (`set_vp_sampled`); the code
/// joins the TP boot agree hash. DEFAULT ON (TP-H2 A/B: sampled thinking-on class -0.72 ms/round at identical
/// trajectories and identical sampled bytes, greedy classes untouched by construction and tie; API thinking-on
/// median +2.4 %). `--tp-vp-sampled off` = the replicated head for those rows (the TP-H..TP-I3 path).
pub const VP_SAMPLED_DEFAULT: u32 = 1;
static VP_SAMPLED: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(VP_SAMPLED_DEFAULT);
pub fn set_vp_sampled(code: u32) { VP_SAMPLED.store(code, AtOrd::Relaxed); }
/// The resolved code (1 = on, 0 = off).
pub fn vp_sampled_code() -> u32 { VP_SAMPLED.load(AtOrd::Relaxed) }
pub fn vp_sampled_on() -> bool { vp_sampled_code() != 0 }
pub fn vp_sampled_desc(code: u32) -> &'static str { if code != 0 { "on" } else { "off" } }
/// Parse the flag's value (None = the flag is absent = the default).
pub fn parse_vp_sampled(v: Option<&str>) -> Result<u32> {
    let Some(s) = v.map(|s| s.trim().to_ascii_lowercase()) else { return Ok(VP_SAMPLED_DEFAULT) };
    match s.as_str() {
        "on" | "1" | "true" => Ok(1),
        "off" | "0" | "false" => Ok(0),
        _ => anyhow::bail!("--tp-vp-sampled takes on|off, got '{s}'"),
    }
}
/// TP-SP1 — `--tp-seq-parallel <on|off>` (a CLI flag, no env): SEQUENCE-PARALLEL prefill (TP-I3 §3.2).
/// For a chunk of T..=SP_MAX rows, rank r owns rows row_block(c, r, W) (rank 0 the first ceil(c/2)):
/// every hc_pre (inject + norm, the hc down/up GEMMs with the full chunk's cuBLASLt plan PINNED on the
/// half-row layouts, silu, mix) runs on the own rows only; the mixers, the router and the EP experts
/// keep all rows after an ALL-GATHER of x (K1m of the own rows + a copy-K2 into the peer's rows); the 96
/// all-reduces become REDUCE-SCATTERS (each rank ships only the peer's rows of its partial and sums
/// only its own); the final streams are gathered once per chunk for the MTP head fill. Bitwise the
/// replicated prefill by construction wherever the pinned-plan gate (--probe-exl3-sppin) holds. The
/// layer-0 block stays replicated when the PLE follows it (the PLE reads every row at the layer-1
/// boundary). The head resolves it and ships the code in TpConfig.exl3_seq_parallel (v22); the node
/// installs the head's value (`set_seq_parallel`); an ON code joins the TP boot agree hash (an OFF boot's
/// hash is the pre-SP one). DEFAULT ON since TP-SP2 (6+6 prefill A/B GO, bitwise; `off` = the replicated prefill).
/// TP-SP2: the code is a bit set. SP_HC (bit 0) = the SP-1 base above; SP_ROUTER (bit 1, only with
/// SP_HC) = the MoE router (the fp32 router GEMM + softmax/top-k) on the own rows too, then ONE
/// all-gather of the ids and weights rows (the router kernels are per-row: one ascending-k chain per
/// (row, expert), one CTA per row for the top-k — bitwise by construction; gate --probe-exl3-sppin's
/// EXL3-SP-ROUTER section). Flag values: off = 0, hc = SP_HC, router = SP_HC | SP_ROUTER, on =
/// SEQ_PAR_ON (the posture the SP-2 A/B picked).
pub const SP_HC: u32 = 1;
pub const SP_ROUTER: u32 = 2;
pub const SEQ_PAR_ON: u32 = SP_HC;
pub const SEQ_PAR_DEFAULT: u32 = SEQ_PAR_ON;
static SEQ_PAR: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(SEQ_PAR_DEFAULT);
pub fn set_seq_parallel(code: u32) { SEQ_PAR.store(code, AtOrd::Relaxed); }
pub fn seq_parallel_code() -> u32 { SEQ_PAR.load(AtOrd::Relaxed) }
pub fn seq_parallel_on() -> bool { seq_parallel_code() & SP_HC != 0 }
/// The router extension is live (SP_ROUTER on top of SP_HC).
pub fn seq_parallel_router() -> bool { seq_parallel_code() & (SP_HC | SP_ROUTER) == (SP_HC | SP_ROUTER) }
pub fn seq_parallel_desc(code: u32) -> &'static str {
    match code { 0 => "off", c if c == SP_HC => "hc", c if c == SP_HC | SP_ROUTER => "hc+router", _ => "?" }
}
/// Parse the flag's value (None = the flag is absent = the default).
pub fn parse_seq_parallel(v: Option<&str>) -> Result<u32> {
    let Some(s) = v.map(|s| s.trim().to_ascii_lowercase()) else { return Ok(SEQ_PAR_DEFAULT) };
    match s.as_str() {
        "on" | "1" | "true" => Ok(SEQ_PAR_ON),
        "hc" => Ok(SP_HC),
        "router" | "hc+router" => Ok(SP_HC | SP_ROUTER),
        "off" | "0" | "false" => Ok(0),
        _ => anyhow::bail!("--tp-seq-parallel takes on|off|hc|router, got '{s}'"),
    }
}
/// The split threshold T: chunks below it stay replicated. TP-I3 §3.1: the pinned hc-down halves are
/// bit-identical for every c >= 97 (and differ at 30 values in [21, 96]); 128 = the margin.
pub const SP_MIN_ROWS: usize = 128;
/// The largest chunk that splits: every chunk the prefill scratch can hold — the served width C = 2048
/// and the C1 tail-checkpoint merges up to 2C - 1 = 4095 rows (TP_MAX_ROWS - 1). The pinned-plan gate
/// (--probe-exl3-sppin, default range = [SP_MIN_ROWS, SP_MAX_ROWS]) covers every c of it.
pub const SP_MAX_ROWS: usize = TP_MAX_ROWS - 1;

/// TP-SP: this rank's row block of a sequence-parallel chunk and the peer's (world 2).
#[derive(Clone, Copy, Debug)]
pub(crate) struct SpRows {
    pub own: (usize, usize),
    pub peer: (usize, usize),
    pub c: usize,
}

/// Rows per gather epoch: 4 x 248,320 B = 993,280 B fits one 1 MiB ring slot (the payload capacity is
/// TP_SLOT_BYTES; the 8 B tail sits after it). Host-checked against n_sh at every launch.
pub(super) const VP_GATHER_ROWS: usize = 4;
/// TP-H2 gate harness ONLY: while set, `vp_greedy` reports false and `vp_gather` true for EVERY row
/// (greedy too), so the gate compares the gathered full rows against the replicated reference.
static GATE_VP_GATHER: AtomicBool = AtomicBool::new(false);
/// TP-H2: the shard width (n_sh) of the built lm_head shard, 0 = none. Set once at model load (before
/// any Scratch exists); Scratch::new sizes its gather buffer from it (TP=1: a 1-element placeholder).
static VP_ROWS_COLS: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
pub(super) fn set_vp_rows_cols(n: usize) { VP_ROWS_COLS.store(n, AtOrd::Relaxed); }
pub(super) fn vp_rows_cols() -> usize { VP_ROWS_COLS.load(AtOrd::Relaxed) }

/// Reduces at or below this size keep the single-block pair (decode/verify: <= 16 rows x 2560 x 4 B
/// = 160 KiB). Prefill chunks (>= 17 rows) take the pipelined pair when the knob is on.
const XPORT_MIN_BYTES: usize = 256 * 1024;

/// --tp-prefill-xport — the prefill all-reduce transport (TP-F; bitwise in every mode):
///   2 / dual / unset : DEFAULT (TP-F A/B GO) — pipelined multi-block K1m/K2m over BOTH ConnectX-7
///                      rails (a second link on --rdma-dev's second entry, default roceP2p1s0f1,
///                      proxy pinned to core TP_AUX_PROXY_CORE); a missing second rail fails the boot
///                      loudly (no silent fallback — set 1 to run on one rail)
///   1 / on           : pipelined multi-block K1m/K2m on the primary rail only
///   0 / off          : the serial single-block K1/K2 pair (the TP-B..E path; diagnostic escape)
/// Rides TpConfig (the EXL3 env snapshot) so both ranks resolve the same value. Tuning
/// (diagnostics): --tp-xport-lookahead (epochs in flight per rail), --tp-xport-blocks.
pub fn prefill_xport_mode() -> u8 {
    match crate::opts::var(crate::opt!("tp-prefill-xport")).map(|v| v.trim().to_ascii_lowercase()) {
        Ok(v) if v == "0" || v == "off" || v == "false" => 0,
        Ok(v) if v == "1" || v == "on" || v == "single" => 1,
        _ => 2,
    }
}

/// TP-I2 item 1 — `--tp-prefill-overlap <off|on|inline[:ROWS]|dual[:ROWS]>` (a CLI flag, no env):
/// comm/compute overlap by row sub-chunks in prefill. At the 96 pipelined prefill reduces (the 48
/// row-parallel mixer out-projections and the 48 EP MoE combines) the per-row consumer that follows
/// the reduce (the mixer's output Hadamard + svh, then the NEXT hc_pre's fused inject + rmsnorm,
/// xq_pf_hc_inj_norm) runs on each landed ROWS-row range (default 128) inside the reduce schedule
/// (`tp_xport::reduce_pipe_hooked`):
///   inline (v1): on the compute stream between the K1m/K2m launches — fills only the wire wait;
///   dual   (v2): the K1m/K2m schedule on the transport's own blocking stream, each landed range
///                handed to the compute stream by an event, so the consumer runs CONCURRENTLY with
///                the K1m/K2m of later epochs (the in-model reduce is K1m/K2m-execution-bound);
///   on = dual:128 (DEFAULT); off = the TP-F path.
/// Bitwise by construction: the same canonical sums, the same per-row kernels on row-offset
/// pointers, every consumed row final. The head resolves it and ships the code in
/// TpConfig.exl3_pf_overlap (rows | dual << 31); the node installs the head's value
/// (`set_pf_overlap`), and the code joins the TP boot agree hash.
pub const PF_OVERLAP_ON_ROWS: u32 = 128;
const PF_DUAL: u32 = 1 << 31;
/// TP-I3 (c1): `fold` — K2m folded into the consumers (xq_pf_hc_inj_norm_k2 / exl3_had_svh_k2 at K2m's
/// schedule position, whole-row epochs, one stream). Code = PF_FOLD | 1 (TpConfig v20).
const PF_FOLD: u32 = 1 << 30;
/// The default posture: `on` = dual:128 (TP-I2 A/B, 6+6 interleaved boots: 32K prefill +1.0%, every pair
/// positive, 128K +1.0%, 2K +1.4%, decode tie, bitwise on every boot). `--tp-prefill-overlap off` = the TP-F path.
pub const PF_OVERLAP_DEFAULT: u32 = PF_OVERLAP_ON_ROWS | PF_DUAL;
static PF_OVERLAP: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(PF_OVERLAP_DEFAULT);
pub fn set_pf_overlap(code: u32) { PF_OVERLAP.store(code, AtOrd::Relaxed); }
/// The resolved code (rows | dual << 31; 0 = off).
pub fn pf_overlap_code() -> u32 { PF_OVERLAP.load(AtOrd::Relaxed) }
/// Hook granularity in rows (0 = off).
pub fn pf_overlap_rows() -> usize { (pf_overlap_code() & !(PF_DUAL | PF_FOLD)) as usize }
/// v2: the transport runs on its own stream.
pub fn pf_overlap_dual() -> bool { pf_overlap_code() & PF_DUAL != 0 }
/// TP-I3 (c1): K2m folded into the consumers.
pub fn pf_overlap_fold() -> bool { pf_overlap_code() & PF_FOLD != 0 }
/// Human form of a code (boot lines).
pub fn pf_overlap_desc(code: u32) -> String {
    if code & PF_FOLD != 0 { return "fold".to_string(); }
    match code & !PF_DUAL { 0 => "off".to_string(), r => format!("{}:{r}", if code & PF_DUAL != 0 { "dual" } else { "inline" }) }
}
/// Parse the flag's value (None = the flag is absent = the default).
pub fn parse_pf_overlap(v: Option<&str>) -> Result<u32> {
    let Some(s) = v.map(|s| s.trim().to_ascii_lowercase()) else { return Ok(PF_OVERLAP_DEFAULT) };
    let bad = || anyhow::anyhow!("--tp-prefill-overlap takes off|on|inline[:ROWS]|dual[:ROWS]|fold, got '{s}'");
    if s == "fold" { return Ok(PF_FOLD | 1); }
    let (mode, rows) = match s.split_once(':') { Some((m, r)) => (m, Some(r)), None => (s.as_str(), None) };
    let rows: u32 = match rows { Some(r) => r.parse().map_err(|_| bad())?, None => PF_OVERLAP_ON_ROWS };
    anyhow::ensure!((1..=TP_MAX_ROWS as u32).contains(&rows), "--tp-prefill-overlap rows {rows} outside 1..={TP_MAX_ROWS}");
    match mode {
        "off" | "0" => Ok(0),
        "on" | "dual" => Ok(rows | PF_DUAL),
        "inline" => Ok(rows),
        _ => Err(bad()),
    }
}

/// TP-I2 item 1: the per-row consumer a hooked prefill reduce runs on each landed row range — the
/// NEXT hc_pre's fused inject + rmsnorm (xq_pf_hc_inj_norm over rows [r0, r1), row-offset pointers).
/// `y` = the reduce's (f16) output, i.e. the pending inject's sublayer output.
#[derive(Clone, Copy, Debug)]
pub(super) struct PfHook {
    pub hn: u64,
    pub resid: u64,
    pub y: u64,
    pub inj: u64,
    pub norm: u64,
    pub h: usize,
    pub hcn: usize,
    pub eps: f32,
    /// hook granularity (rows)
    pub rows: usize,
    /// v2: the K1m/K2m schedule on the transport's own stream (RowHook::side)
    pub dual: bool,
    /// TP-I3 (c1): K2m folded into the consumer (RowHook::fold)
    pub fold: bool,
}

impl PfHook {
    /// xq_pf_hc_inj_norm over rows [r0, r1): grid hc x B, block 128, every pointer offset by r0 rows —
    /// the kernel's (row, stream) CTA reads/writes only its own row, so this is the full-chunk launch's
    /// arithmetic on those rows, bit for bit.
    pub fn inj_norm(&self, l: &Launcher, r0: usize, r1: usize) -> Result<()> {
        let (h, hc, b) = (self.h, self.hcn, r1 - r0);
        xqlaunch!(l, "xq_pf_hc_inj_norm", ((hc * b) as u32, 1, 1), (128, 1, 1), 0,
                  (self.hn + (r0 * hc * h * 2) as u64, self.resid + (r0 * hc * h * 4) as u64,
                   self.y + (r0 * h * 2) as u64, self.inj + (r0 * hc * 4) as u64, self.norm,
                   h as i32, hc as i32, b as i32, self.eps))
    }

    /// TP-I3 (c1): the MoE-site fold — K2m (fp32 partial `part`, fp32 wire, f16 rounding) + the inject+norm
    /// over the epoch's rows [r0, r1), at K2m's schedule position (ctx, lag). hc == 4 (the kernel's groups).
    pub fn inj_norm_k2(&self, l: &Launcher, ctx: u64, lag: u32, part: u64, r0: usize, r1: usize) -> Result<()> {
        let (h, hc) = (self.h, self.hcn);
        anyhow::ensure!(hc == 4 && h % 512 == 0 && h <= 4096, "prefill fold: hc {hc} h {h} outside the fused kernel's shape");
        xqlaunch!(l, "xq_pf_hc_inj_norm_k2", ((r1 - r0) as u32, 1, 1), (512, 1, 1), 0,
                  (ctx, lag, part + (r0 * h * 4) as u64, self.hn + (r0 * hc * h * 2) as u64,
                   self.resid + (r0 * hc * h * 4) as u64, self.inj + (r0 * hc * 4) as u64, self.norm,
                   h as i32, self.eps))
    }
}
/// The dual-rail transport's second proxy core (a big X925; the TP host-worker mask excludes it).
pub const TP_AUX_PROXY_CORE: i32 = 18;
/// Rail-2 TCP handshake port (its liveness responder takes +1).
const TP_AUX_PORT_OFF: u16 = 10;

fn rail2_dev() -> String {
    crate::opts::var(crate::opt!("rdma-dev")).ok().and_then(|s| s.split(',').nth(1).map(|x| x.trim().to_string()))
        .filter(|s| !s.is_empty()).unwrap_or_else(|| "roceP2p1s0f1".to_string())
}

/// TP-I (C6): the post-load boot rendezvous of the dual-rail attach. Probe-tolerant (net_exchange):
/// waits as long as the peer is alive (model-load skew of minutes is legitimate), aborts in bounded
/// time when the peer process is gone (liveness probe every 5 s of silence; a killed peer is
/// noticed <= ~5.5 s after the wait starts or after it dies, an unreachable host <= ~10 s).
/// Frame: [magic, mode]; a magic mismatch is an SPMD desync, a mode mismatch a config desync.
///
/// Test-only failure injection: --tp-boot-delay=<rank>:<seconds> (rides the exl3_env snapshot to
/// the node) sleeps that rank for <seconds> BEFORE the rendezvous — a controlled load skew.
fn boot_rendezvous(rank: i32, mode: u8) -> Result<()> {
    if let Ok(v) = crate::opts::var(crate::opt!("tp-boot-delay")) {
        if let Some((r, s)) = v.split_once(':') {
            if r.trim().parse::<i32>().ok() == Some(rank) {
                let secs: u64 = s.trim().parse().unwrap_or(0);
                println!("[exl3-tp] rank {rank}: --tp-boot-delay test injection — sleeping {secs}s before the boot rendezvous");
                std::thread::sleep(std::time::Duration::from_secs(secs));
            }
        }
    }
    const MAGIC: u32 = 0xB00F_0C06;
    let t0 = std::time::Instant::now();
    println!("[exl3-tp] rank {rank}: entering the post-load boot rendezvous (probe-tolerant, no overall deadline)");
    let peer = crate::net::exchange_u32s(&[MAGIC, mode as u32], 4)
        .context("TP-F dual-rail boot rendezvous (probe-tolerant exchange; peer dead or link aborted)")?;
    if peer[0] != MAGIC || peer[1] != mode as u32 {
        anyhow::bail!("TP-F dual-rail rendezvous: peer frame {:08x}/{} vs mine {MAGIC:08x}/{mode} (SPMD or mode desync)",
                      peer[0], peer[1]);
    }
    println!("[exl3-tp] rank {rank}: boot rendezvous OK after {:.1}s wait (probe-tolerant; mode {mode})",
             t0.elapsed().as_secs_f64());
    Ok(())
}

impl TpState {
    pub fn attach(dev: &Arc<CudaDevice>, t: TpAttach, h: usize) -> Result<Self> {
        anyhow::ensure!(t.world == 2, "EXL3 TP: rung 3 supports world 2 only (got {})", t.world);
        let kern = crate::tp_xport::Kernels::load(dev, TP_MODULE)?;
        let mut link = t.link;
        // DEFAULT payload = one fp32 hidden row (per-barrier lengths are explicit at every site).
        link.set_payload(h * 4, true).context("net_set_payload")?;
        let trace = crate::opts::var(crate::opt!("tp-trace")).is_ok() || crate::tp::tp_config().map_or(false, |c| c.trace);
        if trace {
            crate::net::trace_enable(&mut link);
            println!("[exl3-tp] per-barrier tracing ON");
        }
        let ctx = link.ctx_device_ptr();
        let addr = link.ctx_addr();
        let peer_ip = link.peer_ip();
        // The proxy OWNS the transport from here (gpu.rs attach_tp contract); the OS reclaims at exit.
        std::mem::forget(link);
        crate::net::spawn_proxy(addr, TP_PROXY_CORE);
        let part = dev.alloc_zeros::<f32>(TP_MAX_ROWS * h)?;
        let mode = prefill_xport_mode();
        let mut aux: Option<usize> = None;
        let xport = if mode > 0 {
            let mut rails = vec![ctx];
            if mode == 2 {
                // Rendezvous on the primary link first (both ranks are inside attach), so rank 1 never
                // dials rail 2 before rank 0 listens; the frame carries the mode (SPMD check).
                // TP-I (audit C6): this is the FIRST cross-rank sync after each rank's independent
                // shard load (50-220 s, skewed by page-cache warmth), so it must tolerate minutes of
                // legitimate skew. It used to be a 10 s net_agree (abort code 7: a cold-cache rank
                // failed the boot). It is now the probe-tolerant net_exchange: no overall deadline,
                // a dead peer is still caught by the out-of-band liveness probe (every
                // TP_LIVE_PROBE_NS = 5 s of silence, two failed connects -> abort code 10). Live-round
                // deadlines (step_go / pre_verify / tp_round / net_agree) are untouched.
                boot_rendezvous(t.rank, mode)?;
                let dev2 = rail2_dev();
                let port = crate::tp::TP_PORT + TP_AUX_PORT_OFF;
                if t.rank != 0 { std::thread::sleep(std::time::Duration::from_millis(300)); }
                let mut l2 = crate::net::TpLink::connect(t.rank, if t.rank == 0 { "" } else { &peer_ip }, port, &dev2,
                                                         crate::tp::GID_IDX, crate::tp::TP_SLOT_BYTES)
                    .with_context(|| format!("TP-F rail 2 ({dev2}, port {port}, peer {peer_ip})"))?;
                l2.set_payload(h * 4, true).context("rail 2 net_set_payload")?;
                rails.push(l2.ctx_device_ptr());
                let a2 = l2.ctx_addr();
                std::mem::forget(l2);
                crate::net::spawn_proxy_aux(a2, TP_AUX_PROXY_CORE);
                aux = Some(a2);
                println!("[exl3-tp] rank {} rail 2 UP: {dev2} (TCP {port}, peer {peer_ip}), proxy pinned to core {TP_AUX_PROXY_CORE}", t.rank);
            }
            let lookahead = crate::opts::var(crate::opt!("tp-xport-lookahead")).ok().and_then(|v| v.parse().ok()).unwrap_or(4usize);
            let blocks = crate::opts::var(crate::opt!("tp-xport-blocks")).ok().and_then(|v| v.parse().ok()).unwrap_or(16u32);
            Some(crate::tp_xport::Pipe::new(dev, rails, t.world as usize, lookahead, blocks)?)
        } else { None };
        let dec = if dec_xport_mode() == 1 {
            let mut arrive = dev.alloc_zeros::<u32>(1)?;
            dev.memset_zeros(&mut arrive)?;   // AGENTS §2.2: alloc_zeros does not zero
            let grecv = crate::opts::var(crate::opt!("tp-dec-grecv")).map_or(true, |v| v.trim() != "0");
            let blocks = crate::opts::var(crate::opt!("tp-dec-blocks")).ok().and_then(|v| v.parse().ok()).unwrap_or(8u32).clamp(1, 64);
            Some(DecXport { arrive, grecv, blocks })
        } else { None };
        dev.synchronize()?;
        match &dec {
            Some(d) => println!("[exl3-tp] decode transport: K1 FOLDED into the producers + multi-block K2 ({} blocks, f16 cvt folded), \
                                 receive {} (--tp-dec-xport default; =0 = the serial pair)", d.blocks,
                                if d.grecv { "GPU-side (payload tail) or cpu_done" } else { "cpu_done only (--tp-dec-grecv=0)" }),
            None => println!("[exl3-tp] decode transport: serial single-block K1/K2 + cvt (--tp-dec-xport=0)"),
        }
        println!("[exl3-tp] rank {}/{} attached: fp32 all-reduce, proxy pinned to core {TP_PROXY_CORE}, \
                  EP deal '{}', partial buffer {} rows", t.rank, t.world, ep_deal_kind(), TP_MAX_ROWS);
        match &xport {
            Some(x) => println!("[exl3-tp] prefill transport: PIPELINED multi-block (--tp-prefill-xport) — \
                                 {} rail(s), lookahead {} epochs/rail, {} blocks, reduces > {} KiB",
                                 x.rails.len(), x.lookahead, x.blocks, XPORT_MIN_BYTES / 1024),
            None => println!("[exl3-tp] prefill transport: serial single-block K1/K2 (--tp-prefill-xport=0)"),
        }
        match pf_overlap_rows() {
            0 => println!("[exl3-tp] prefill overlap: OFF (--tp-prefill-overlap off)"),
            _ if pf_overlap_fold() => println!("[exl3-tp] prefill overlap: FOLD — whole-row epochs, each epoch's K2m replaced \
                           by the fused consumer (xq_pf_hc_inj_norm_k2 / exl3_had_svh_k2 + inject+norm), one stream \
                           (--tp-prefill-overlap fold)"),
            r => println!("[exl3-tp] prefill overlap: ON — the next hc_pre's inject+norm (and the mixer's svh) run per \
                           landed {r}-row range inside each pipelined prefill reduce, {} (--tp-prefill-overlap {})",
                          if pf_overlap_dual() { "K1m/K2m on the transport's own stream (dual)" } else { "same stream (inline)" },
                          pf_overlap_desc(pf_overlap_code())),
        }
        if seq_parallel_on() {
            println!("[exl3-tp] TP-SP sequence-parallel prefill: ON (--tp-seq-parallel {}) — chunks of {SP_MIN_ROWS}..={SP_MAX_ROWS} \
                      rows: hc_pre on the own row block (rank 0 the first ceil(c/2) rows, hc GEMM plans pinned to the full \
                      chunk's), x all-gathered before every mixer / router, reduce-scatters instead of all-reduces{}{}",
                     seq_parallel_desc(seq_parallel_code()),
                     if seq_parallel_router() { "; the MoE router on the own rows + one ids/weights all-gather per layer (SP-2)" } else { "" },
                     if xport.is_some() { "" } else { " — INACTIVE: needs the pipelined transport (--tp-prefill-xport != 0)" });
        }
        Ok(TpState { rank: t.rank, world: t.world, ctx, part, xport, kern, aux, dec })
    }

    /// In-place FP32 sum-all-reduce of `n` floats at device address `p` (world 2): K1 publishes
    /// the local partial, K2 (mode 2) waits for the peer's and writes rank0 + rank1 (canonical
    /// order on BOTH ranks => bit-identical results), no rounding. Both on the blocking stream.
    /// TP-B: payloads larger than one ring slot (prefill: 2048 x 2560 x 4 B = 21 MB) run as
    /// consecutive epochs of <= TP_EPOCH_FLOATS each (the existing per-epoch rings; the same
    /// elementwise canonical sum, so the result is independent of the chunking).
    fn all_reduce_f32(&self, l: &Launcher, p: u64, n: usize) -> Result<()> {
        if let Some(x) = &self.xport {
            if let Some(a) = self.aux {
                // rail 2 is invisible to the agrees (they ride rail 1): surface its abort there (I9)
                let st = crate::net::ctx_abort_status(a);
                if st != 0 {
                    crate::net::abort_link();
                    anyhow::bail!("TP-F rail 2 transport ABORT (status {st}) — aborting the primary link");
                }
            }
            if n * 4 > XPORT_MIN_BYTES && crate::tp_xport::pipe_ok(n) {
                return crate::tp_xport::reduce_pipe(&self.kern, l.stream, x, crate::tp_xport::Io::f32_inplace(p), n);
            }
        }
        crate::tp_xport::reduce_serial(&self.kern, l.stream, self.ctx, p, n)
    }

    /// TP-F fused prefill reduce: the local partial at `io.src` (f16 or f32) -> canonical fp32 sum ->
    /// `io.out` (f16: one __float2half_rn rounding, exactly the xq_cvt_f32_f16 the unfused path runs).
    /// Returns false (nothing launched) when the pipelined transport does not take this reduce — the
    /// caller then runs its explicit cvt + all_reduce_f32 + cvt sequence.
    fn all_reduce_io(&self, io: crate::tp_xport::Io, n: usize) -> Result<Option<crate::tp_xport::Io>> {
        match &self.xport {
            // world>2 (rounds > 1): round k's local is round k-1's fp32 SUM, which an f16 in-place
            // buffer would round between rounds (output-changing) — those worlds take the explicit
            // cvt + fp32 all-reduce + cvt path until an fp32 intermediate is wired (TP-F.md §7).
            Some(x) if x.rounds == 1 && n * 4 > XPORT_MIN_BYTES && crate::tp_xport::pipe_ok(n) => Ok(Some(io)),
            _ => Ok(None),
        }
    }

    fn reduce_io(&self, l: &Launcher, io: crate::tp_xport::Io, n: usize) -> Result<()> {
        self.reduce_io_hooked(l, io, n, None)
    }

    /// reduce_io with the TP-I2 rows-landed hook (None = reduce_io).
    fn reduce_io_hooked(&self, l: &Launcher, io: crate::tp_xport::Io, n: usize,
                        hook: Option<crate::tp_xport::RowHook<'_>>) -> Result<()> {
        let x = self.xport.as_ref().context("reduce_io without the pipelined transport")?;
        if let Some(a) = self.aux {
            let st = crate::net::ctx_abort_status(a);
            if st != 0 {
                crate::net::abort_link();
                anyhow::bail!("TP-F rail 2 transport ABORT (status {st}) — aborting the primary link");
            }
        }
        crate::tp_xport::reduce_pipe_hooked(&self.kern, l.stream, x, io, n, hook)
    }

    fn part_ptr(&self) -> u64 { *self.part.device_ptr() as u64 }

    /// TP-SP: the exchanges need the pipelined transport at world 2 (one exchange round).
    pub(super) fn sp_ready(&self) -> bool {
        self.world == 2 && self.xport.as_ref().map_or(false, |x| x.rounds == 1)
    }

    /// The rail-2 abort surfaced on the primary link (rail 2 is invisible to the agrees, I9).
    fn rail2_check(&self) -> Result<()> {
        if let Some(a) = self.aux {
            let st = crate::net::ctx_abort_status(a);
            if st != 0 {
                crate::net::abort_link();
                anyhow::bail!("TP-F rail 2 transport ABORT (status {st}) — aborting the primary link");
            }
        }
        Ok(())
    }

    /// TP-SP: all-gather `row_bytes`-byte rows at `base` — this rank's own rows to the peer, the peer's
    /// own rows into this rank's buffer (a bit copy both ways).
    pub(super) fn sp_all_gather(&self, l: &Launcher, base: u64, row_bytes: usize, sp: &SpRows) -> Result<()> {
        let x = self.xport.as_ref().context("TP-SP all-gather without the pipelined transport")?;
        self.rail2_check()?;
        crate::tp_xport::all_gather_rows(&self.kern, l.stream, x, base, row_bytes, sp.own, sp.peer)
    }

    /// TP-SP2: all-gather several row buffers of the same row blocks in ONE exchange program (the
    /// router's ids + weights rows).
    pub(super) fn sp_all_gather_multi(&self, l: &Launcher, bufs: &[(u64, usize)], sp: &SpRows) -> Result<()> {
        let x = self.xport.as_ref().context("TP-SP all-gather without the pipelined transport")?;
        self.rail2_check()?;
        crate::tp_xport::all_gather_rows_multi(&self.kern, l.stream, x, bufs, sp.own, sp.peer)
    }

    /// TP-SP: reduce-scatter a c-row partial (`io` as reduce_io, row_len elements per row): the canonical
    /// sum lands in this rank's own rows of io.out only; `hook` = the dual overlap on the own rows.
    pub(super) fn sp_reduce_scatter(&self, l: &Launcher, io: crate::tp_xport::Io, row_len: usize, sp: &SpRows,
                                    hook: Option<crate::tp_xport::SpHook<'_>>) -> Result<()> {
        let x = self.xport.as_ref().context("TP-SP reduce-scatter without the pipelined transport")?;
        self.rail2_check()?;
        crate::tp_xport::reduce_scatter_rows(&self.kern, l.stream, x, io, row_len, sp.own, sp.peer, hook)
    }

    /// TP-H #3: the device address of the doorbell context (the first argument of every folded K1 / K2).
    pub(super) fn ctx_addr(&self) -> u64 { self.ctx }

    /// TP-H #3: the K1 arrive counter of the decode transport (None = the serial pair: no folds).
    pub(super) fn dec_arrive(&self) -> Option<u64> { self.dec.as_ref().map(|d| *d.arrive.device_ptr() as u64) }

    /// TP-H #3 K2: out[n] (fp32) = canonical lower + upper of `local` (this rank's zero-padded fp32 block
    /// maxima) and the peer's payload of the epoch the preceding xq_dh_screen_k1 published.
    pub(super) fn dh_bmax_k2(&self, l: &Launcher, out: u64, local: u64, n: usize) -> Result<()> {
        let d = self.dec.as_ref().context("the sharded DHEAD screen without the decode transport")?;
        anyhow::ensure!(self.world == 2 && n % 4 == 0, "the sharded DHEAD screen K2: world {} n {n}", self.world);
        self.dec_k2(l, d, out, local, n, false, false)
    }

    /// TP-G decode K2: out (f16 when `out_f16`) = canonical lower + upper of `local` (f16 when
    /// `local_f16`) and the peer's fp32 payload of the epoch the preceding folded K1 published.
    fn dec_k2(&self, l: &Launcher, d: &DecXport, out: u64, local: u64, n: usize, local_f16: bool, out_f16: bool) -> Result<()> {
        let io = (local_f16 as i32) | ((out_f16 as i32) << 1) | ((d.grecv as i32) << 3);
        xqlaunch!(l, "xq_tp_wait_add_dec", (d.blocks, 1, 1), (256, 1, 1), 0, (self.ctx, out, local, n as i32, io))
    }

    /// TP-G: this reduce takes the folded decode path (world 2, decode-sized, float4-clean).
    fn dec_ok(&self, n: usize) -> Option<&DecXport> {
        self.dec.as_ref().filter(|_| self.world == 2 && n % 4 == 0 && n * 4 <= XPORT_MIN_BYTES)
    }
}

impl FwdModel {
    /// TP-H #4: the vocab-parallel greedy tail (shard GEMM -> local argmax keys -> one key exchange
    /// -> merged ids in sc.argmax). Only a greedy, unpenalized, non-ratio-rule step / verify round
    /// with <= 16 rows takes it; everything else runs the replicated head.
    pub(super) fn vp_greedy(&self, sc: &Scratch, m: usize) -> bool {
        self.lm_head_vp.is_some() && (1..=16).contains(&m) && !sc.samp_live && !sc.pen_live && !sc.rq_live
            && !GATE_VP_OFF.load(AtOrd::Relaxed) && !GATE_VP_GATHER.load(AtOrd::Relaxed)
    }

    /// TP-H2 (`--tp-vp-sampled`): the rows vp_greedy refuses (sampled / penalized / ratio-rule) take the
    /// shard GEMM + row all-gather tail (vp_gather_rows) and then the unchanged pen / argmax / sampler.
    pub(super) fn vp_gather(&self, sc: &Scratch, m: usize) -> bool {
        if self.lm_head_vp.is_none() || !(1..=16).contains(&m) || GATE_VP_OFF.load(AtOrd::Relaxed) { return false; }
        if GATE_VP_GATHER.load(AtOrd::Relaxed) { return true; }
        vp_sampled_on() && (sc.samp_live || sc.pen_live || sc.rq_live)
    }

    /// Graph-key bits for the vp tails: bit 45 = the greedy key-exchange tail (TP-H #4), bit 46 = the
    /// TP-H2 row all-gather tail. Both are capture-time properties of the graph.
    pub(super) fn vp_key(&self, sc: &Scratch, m: usize) -> usize {
        ((self.vp_greedy(sc, m) as usize) << 45) | ((self.vp_gather(sc, m) as usize) << 46)
    }

    /// TP-H2: the shard GEMM into sc.vp_rows [m][n_sh], then the row all-gather into sc.logits [m][V]
    /// (this rank's columns by K1, the peer's by K2). sc.logits rows 0..m are then the replicated
    /// head's rows bit for bit on both ranks. Launches only (graph-capturable; the epoch is derived on
    /// device, every launch argument is a per-width constant).
    pub(super) fn vp_gather_rows(&self, l: &Launcher, sc: &mut Scratch, m: usize) -> Result<()> {
        let vp = self.lm_head_vp.as_ref().context("vp_gather_rows without the lm_head shard")?;
        let tp = self.tp.as_ref().context("vp_gather_rows without a TP attachment")?;
        let d = tp.dec.as_ref().context("vp_gather_rows without the decode transport")?;
        anyhow::ensure!(tp.world == 2, "the vocab-parallel row gather is world 2 only (world {})", tp.world);
        let v = self.cfg.vocab_size;
        let n_sh = vp.n_sh as usize;
        anyhow::ensure!(n_sh * 2 == v && n_sh % 8 == 0 && v % 8 == 0 && (vp.base as usize) % 8 == 0,
                        "vp gather: shard {n_sh} / vocab {v} / base {} not 16 B aligned halves", vp.base);
        anyhow::ensure!(VP_GATHER_ROWS * n_sh * 2 + 8 <= crate::tp::TP_SLOT_BYTES,
                        "vp gather: {VP_GATHER_ROWS} rows x {n_sh} halves exceed one ring slot");
        anyhow::ensure!(m * n_sh <= sc.vp_rows.len() && m * v <= sc.logits.len(),
                        "vp gather: m {m} exceeds the scratch (vp_rows {}, logits {})", sc.vp_rows.len(), sc.logits.len());
        // the shard's fused-Hadamard logits (the TP-H #4 shard Quad; ks = 1 asserted at build)
        exl3_chain(l, &vp.q, &sc.x, &mut sc.chain_xh, &mut sc.chain_yraw, &mut sc.vp_rows, m, &sc.chain_ws)?;
        let arrive = *d.arrive.device_ptr() as u64;
        let (own, peer) = (vp.base, (tp.rank ^ 1) * vp.n_sh);
        let ne = m.div_ceil(VP_GATHER_ROWS);
        let blocks = |nr: usize| ((nr * n_sh / 8).div_ceil(256 * 8) as u32).clamp(1, 32);
        for j in 0..ne {
            let (r0, nr) = (j * VP_GATHER_ROWS, VP_GATHER_ROWS.min(m - j * VP_GATHER_ROWS));
            xqlaunch_raw!(l, "xq_vp_gather_k1", (blocks(nr), 1, 1), (256, 1, 1), 0,
                          (tp.ctx, &sc.vp_rows, &mut sc.logits, v as i64, vp.n_sh, own, r0 as i32, nr as i32, arrive))?;
        }
        for j in 0..ne {
            let (r0, nr) = (j * VP_GATHER_ROWS, VP_GATHER_ROWS.min(m - j * VP_GATHER_ROWS));
            let lag = (ne - 1 - j) as u32;
            xqlaunch_raw!(l, "xq_vp_gather_k2", (blocks(nr), 1, 1), (256, 1, 1), 0,
                          (tp.ctx, &mut sc.logits, v as i64, vp.n_sh, peer, r0 as i32, nr as i32, lag,
                           (d.grecv as i32) << 3))?;
        }
        Ok(())
    }

    pub(super) fn vp_greedy_tail(&self, l: &Launcher, sc: &mut Scratch, m: usize) -> Result<()> {
        let vp = self.lm_head_vp.as_ref().context("vp_greedy_tail without the lm_head shard")?;
        let tp = self.tp.as_ref().context("vp_greedy_tail without a TP attachment")?;
        let d = tp.dec.as_ref().context("vp_greedy_tail without the decode transport")?;
        // the shard's fused-Hadamard logits land in the first m * n_sh entries of sc.logits (the
        // full-row buffer is idle on this path)
        exl3_chain(l, &vp.q, &sc.x, &mut sc.chain_xh, &mut sc.chain_yraw, &mut sc.logits, m, &sc.chain_ws)?;
        let nbytes = 8 * ((m + 1) & !1);
        let arrive = *d.arrive.device_ptr() as u64;
        let nb = wp09_am_nb(m);
        anyhow::ensure!(m <= sc.am_cnt.len(), "vp tail: m {m} > scratch width {}", sc.am_cnt.len());
        xqlaunch_raw!(l, "xq_argmax_rows_vp", (nb as u32, m as u32, 1), (256, 1, 1), 0,
                 (tp.ctx, &mut sc.vp_keys, &sc.logits, vp.n_sh as i64, vp.n_sh as i32, vp.base,
                  &mut sc.am_part, &mut sc.am_cnt, arrive, nbytes as u32))?;
        xqlaunch_raw!(l, "xq_tp_wait_keys", (1u32, 1, 1), (32, 1, 1), 0,
                 (tp.ctx, &mut sc.vp_keys, &mut sc.argmax, m as i32, nbytes as i32, (d.grecv as i32) << 3))
    }

    pub fn tp_rank(&self) -> Option<(i32, i32)> { self.tp.as_ref().map(|t| (t.rank, t.world)) }

    /// TP-A rung 3: turn this rank's routed experts (+ the replicated shared expert on rank 0)
    /// into the full-rank moe_out: FP32 partial -> all-reduce -> one f16 rounding.
    pub(super) fn ep_combine_reduce(&self, l: &Launcher, sc: &mut Scratch, moe: &MoeLayer, ep: &EpShard,
                                    m: usize) -> Result<()> {
        let tp = self.tp.as_ref().context("an expert-parallel MoE layer without a TP attachment")?;
        anyhow::ensure!(ep.rank == tp.rank as usize && ep.world == tp.world as usize,
            "EP shard rank {}/{} != attached TP rank {}/{}", ep.rank, ep.world, tp.rank, tp.world);
        let h = self.cfg.hidden_size;
        let topk = self.cfg.num_experts_per_tok;
        let n = m * h;
        anyhow::ensure!(n <= tp.part.len(), "EP combine: m={m} exceeds the partial buffer ({TP_MAX_ROWS} rows)");
        let part = *tp.part.device_ptr() as u64;
        if let Some(d) = tp.dec_ok(n) {
            // TP-G: combine + K1 in one launch, then K2 writes moe_out (f16) directly
            let arrive = *d.arrive.device_ptr() as u64;
            xqlaunch_raw!(l, "xq_moe_combine_ep_k1l", (m as u32, 1, 1), (1024, 1, 1), 4096,
                     (tp.ctx, part, &sc.yd, &sc.ysh, &sc.ids, &sc.wts, &sc.slotmap, &moe.sg, &sc.x,
                      topk as i32, h as i32, m as i32, (ep.shared_split || ep.rank == 0) as i32, arrive))?;
            let mo = *sc.moe_out.device_ptr() as u64;
            return tp.dec_k2(l, d, mo, part, n, false, true);
        }
        xqlaunch!(l, "xq_moe_combine_ep", (m as u32, 1, 1), (1024, 1, 1), 4096,
                 (part, &sc.yd, &sc.ysh, &sc.ids, &sc.wts, &sc.slotmap, &moe.sg, &sc.x,
                  topk as i32, h as i32, m as i32, (ep.shared_split || ep.rank == 0) as i32))?;
        tp.all_reduce_f32(l, part, n)?;
        xqlaunch!(l, "xq_cvt_f32_f16", ((n as u32).div_ceil(256), 1, 1), (256, 1, 1), 0,
                 (&mut sc.moe_out, part, n as i64))?;
        Ok(())
    }
}

impl FwdModel {
    /// TP-B: the out-projection chain of a mixer. A row-parallel Quad (ShardSpec::Row — this
    /// rank holds a K slice) produces a PARTIAL: chain_rowpar reduces it; any other Quad is the
    /// plain served chain.
    #[allow(clippy::too_many_arguments)]
    pub(super) fn chain_o(&self, l: &Launcher, q: &Quad, x: &CudaSlice<u16>, xh: &mut CudaSlice<u16>,
                          yraw: &mut CudaSlice<u16>, y: &mut CudaSlice<u16>, m: usize, ws: &CudaSlice<f32>) -> Result<()> {
        if q.rowpar { self.chain_rowpar(l, q, x, xh, yraw, y, m, ws, None, None, None).map(|_| ()) } else { exl3_chain(l, q, x, xh, yraw, y, m, ws) }
    }

    /// chain_o for the prefill (m = c) sites: the plain arm is exl3_chain_rb (recon + cuBLASLt).
    /// TP-I2 item 1: `hook` = the next hc_pre's inject+norm to run per landed row range inside the
    /// row-parallel reduce. Returns true iff the hook ran (every row), i.e. the caller must NOT run
    /// that inject+norm again. TP-SP: `sp` = this rank's row block of a sequence-parallel chunk — the
    /// reduce becomes a reduce-scatter and y (+ the hook) is produced for the OWN rows only.
    #[allow(clippy::too_many_arguments)]
    pub(super) fn chain_o_rb(&self, l: &Launcher, q: &Quad, x: &CudaSlice<u16>, xh: &mut CudaSlice<u16>,
                             yraw: &mut CudaSlice<u16>, y: &mut CudaSlice<u16>, m: usize, ws: &CudaSlice<f32>,
                             rb: &ReconBufs, hook: Option<PfHook>, sp: Option<SpRows>) -> Result<bool> {
        if q.rowpar {
            pf_chain_check_n(q, m, xh, yraw)?;
            self.chain_rowpar(l, q, x, xh, yraw, y, m, ws, Some(rb), hook, sp)
        } else {
            anyhow::ensure!(sp.is_none(), "TP-SP: a sequence-parallel chunk reached a non-row-parallel out projection");
            exl3_chain_rb(l, q, x, xh, yraw, y, m, ws, rb).map(|_| false)
        }
    }

    /// TP-B row-parallel chain: y = svh ⊙ H_N( Σ_ranks W_rᵀ·H_K(x_r ⊙ suh_r) ). Each rank computes
    /// its K-slice's y_raw partial in FP32 (m <= 16: the split-K GEMM's fp32 slabs summed in the
    /// ascending order of exl3_ks_combine, NO f16 rounding; m > 16: the served wide / recon GEMM's
    /// f16 y_raw, widened), ONE FP32 all-reduce (canonical rank0 + rank1 on both ranks), then the
    /// SAME single f16 rounding + output Hadamard/svh as the TP=1 chain. Batch invariance: every
    /// step is per row with an m-independent ks (chain_ks of the per-rank shape).
    #[allow(clippy::too_many_arguments)]
    fn chain_rowpar(&self, l: &Launcher, q: &Quad, x: &CudaSlice<u16>, xh: &mut CudaSlice<u16>,
                    yraw: &mut CudaSlice<u16>, y: &mut CudaSlice<u16>, m: usize, ws: &CudaSlice<f32>,
                    rb: Option<&ReconBufs>, hook: Option<PfHook>, sp: Option<SpRows>) -> Result<bool> {
        let tp = self.tp.as_ref().context("a row-parallel Quad without a TP attachment")?;
        let n = q.n as usize;
        let mn = m * n;
        anyhow::ensure!(mn <= tp.part.len(), "row-parallel chain m={m} N={n} exceeds the TP partial buffer ({})", tp.part.len());
        anyhow::ensure!(mn <= yraw.len() && mn <= y.len(), "row-parallel chain m={m} N={n}: y_raw/y too small");
        let part = tp.part_ptr();
        let g = |e: usize| (((e + 255) / 256) as u32, 1, 1);
        if m <= 16 {
            xqlaunch!(l, "exl3_had_suh", (m as u32 * (q.k as u32 / 128), 1, 1), (32, 1, 1), 0, (x, &q.suh, &mut *xh, q.k))?;
            if let Some(d) = tp.dec_ok(mn) {
                // TP-G: the partial's producer carries K1; K2 writes the f16 y_raw (the cvt folded)
                let arrive = *d.arrive.device_ptr() as u64;
                let yp = *yraw.device_ptr() as u64;
                if q.ks > 1 {
                    let kb = (q.k as u32) / 16;
                    anyhow::ensure!(kb % q.ks == 0, "chain ks {} does not divide kb {}", q.ks, kb);
                    anyhow::ensure!(q.ks as usize * mn <= ws.len(), "chain_ws too small: need {} have {}", q.ks as usize * mn, ws.len());
                    xqlaunch!(l, "exl3_hmma_gemm_ks", ((q.n as u32) / 128, q.ks, 1), (256, 1, 1), 0,
                             (&q.tr, &mut *xh, ws, m as i32, q.k, q.n, q.bits))?;
                    xqlaunch!(l, "xq_ks_combine_f32_k1l", g(mn), (256, 1, 1), 0,
                             (tp.ctx, ws, part, m as i32, q.n, q.ks as i32, arrive))?;
                } else {
                    xqlaunch!(l, "exl3_hmma_gemm", ((q.n as u32) / 128, 1, 1), (256, 1, 1), 0,
                             (&q.tr, &mut *xh, &mut *yraw, m as i32, q.k, q.n, q.bits))?;
                    xqlaunch!(l, "xq_cvt_f16_f32_k1l", g(mn), (256, 1, 1), 0, (tp.ctx, part, yp, mn as i32, arrive))?;
                }
                tp.dec_k2(l, d, yp, part, mn, false, true)?;
                xqlaunch!(l, "exl3_had_svh", (m as u32 * (q.n as u32 / 128), 1, 1), (32, 1, 1), 0, (&*yraw, &q.svh, &mut *y, q.n))?;
                return Ok(false);
            }
            if q.ks > 1 {
                let kb = (q.k as u32) / 16;
                anyhow::ensure!(kb % q.ks == 0, "chain ks {} does not divide kb {}", q.ks, kb);
                anyhow::ensure!(q.ks as usize * mn <= ws.len(), "chain_ws too small: need {} have {}", q.ks as usize * mn, ws.len());
                xqlaunch!(l, "exl3_hmma_gemm_ks", ((q.n as u32) / 128, q.ks, 1), (256, 1, 1), 0,
                         (&q.tr, &mut *xh, ws, m as i32, q.k, q.n, q.bits))?;
                xqlaunch!(l, "xq_ks_combine_f32", g(mn), (256, 1, 1), 0, (ws, part, m as i32, q.n, q.ks as i32))?;
            } else {
                xqlaunch!(l, "exl3_hmma_gemm", ((q.n as u32) / 128, 1, 1), (256, 1, 1), 0,
                         (&q.tr, &mut *xh, &mut *yraw, m as i32, q.k, q.n, q.bits))?;
                xqlaunch!(l, "xq_cvt_f16_f32", g(mn), (256, 1, 1), 0, (part, &*yraw, mn as i64))?;
            }
        } else {
            chain_wide_raw(l, q, x, xh, yraw, m, rb)?;
            if let Some(sp) = sp {
                // TP-SP: every rank's partial over ALL rows (the mixer ran on the gathered x) ->
                // reduce-scatter on the lossless f16 wire (each rank ships the peer's rows, sums its own:
                // the all-reduce's canonical fp32 sum + single f16 rounding on those rows) -> the output
                // Hadamard + svh on the OWN rows (one CTA = one (row, 128-block): row-offset pointers).
                anyhow::ensure!(sp.c == m, "TP-SP: chunk {} vs chain m {m}", sp.c);
                let yp = *yraw.device_ptr() as u64;
                let (svh, yo) = (*q.svh.device_ptr() as u64, *y.device_ptr() as u64);
                let io = crate::tp_xport::Io { src: yp, src_f16: true, out: yp, out_f16: true, wire_f16: true };
                if let Some(hk) = hook {
                    anyhow::ensure!(hk.y == yo, "prefill overlap hook: y {:#x} is not this chain's output {yo:#x}", hk.y);
                    let mut f = |r0: usize, r1: usize| -> Result<()> {
                        xqlaunch!(l, "exl3_had_svh", (((r1 - r0) * (n / 128)) as u32, 1, 1), (32, 1, 1), 0,
                                  (yp + (r0 * n * 2) as u64, svh, yo + (r0 * n * 2) as u64, q.n))?;
                        hk.inj_norm(l, r0, r1)
                    };
                    tp.sp_reduce_scatter(l, io, n, &sp, Some(crate::tp_xport::SpHook { min_rows: hk.rows, side: hk.dual, f: &mut f }))?;
                    return Ok(true);
                }
                tp.sp_reduce_scatter(l, io, n, &sp, None)?;
                let (r0, r1) = sp.own;
                xqlaunch!(l, "exl3_had_svh", (((r1 - r0) * (n / 128)) as u32, 1, 1), (32, 1, 1), 0,
                          (yp + (r0 * n * 2) as u64, svh, yo + (r0 * n * 2) as u64, q.n))?;
                return Ok(false);
            }
            // TP-F: y_raw (f16) -> f16 wire (exact: y_raw IS the partial) -> canonical fp32 sum -> y_raw
            // (f16, one __float2half_rn) — the two cvt passes fused, half the wire bytes
            let yp = *yraw.device_ptr() as u64;
            if let Some(io) = tp.all_reduce_io(crate::tp_xport::Io { src: yp, src_f16: true, out: yp, out_f16: true, wire_f16: true }, mn)? {
                if let Some(hk) = hook {
                    // TP-I2 item 1: per landed row range, the output Hadamard + svh (exl3_had_svh's CTA =
                    // one (row, 128-block): row-offset pointers give the full launch's bits on those
                    // rows), then the next hc_pre's inject+norm reading the rows just written.
                    let (svh, yo) = (*q.svh.device_ptr() as u64, *y.device_ptr() as u64);
                    anyhow::ensure!(hk.y == yo, "prefill overlap hook: y {:#x} is not this chain's output {yo:#x}", hk.y);
                    let mut f = |r0: usize, r1: usize| -> Result<()> {
                        xqlaunch!(l, "exl3_had_svh", (((r1 - r0) * (n / 128)) as u32, 1, 1), (32, 1, 1), 0,
                                  (yp + (r0 * n * 2) as u64, svh, yo + (r0 * n * 2) as u64, q.n))?;
                        hk.inj_norm(l, r0, r1)
                    };
                    // TP-I3 (c1) fold: K2m + exl3_had_svh fused per whole-row epoch (the local partial is y_raw,
                    // which the fold never overwrites), then the inject+norm of those rows
                    let mut fk = |ctx: u64, lag: u32, r0: usize, r1: usize| -> Result<()> {
                        let tasks = (r1 - r0) * (n / 128);
                        xqlaunch!(l, "exl3_had_svh_k2", (tasks.div_ceil(8).min(96) as u32, 1, 1), (256, 1, 1), 0,
                                  (ctx, lag, yp + (r0 * n * 2) as u64, svh, yo + (r0 * n * 2) as u64, q.n, (r1 - r0) as i32))?;
                        hk.inj_norm(l, r0, r1)
                    };
                    let fold: Option<&mut dyn FnMut(u64, u32, usize, usize) -> Result<()>> = if hk.fold { Some(&mut fk) } else { None };
                    tp.reduce_io_hooked(l, io, mn, Some(crate::tp_xport::RowHook { row_len: n, min_rows: hk.rows, f: &mut f,
                                                                                   side: hk.dual, fold }))?;
                    return Ok(true);
                }
                tp.reduce_io(l, io, mn)?;
                xqlaunch!(l, "exl3_had_svh", (m as u32 * (q.n as u32 / 128), 1, 1), (32, 1, 1), 0, (&*yraw, &q.svh, &mut *y, q.n))?;
                return Ok(false);
            }
            xqlaunch!(l, "xq_cvt_f16_f32", g(mn), (256, 1, 1), 0, (part, &*yraw, mn as i64))?;
        }
        tp.all_reduce_f32(l, part, mn)?;
        xqlaunch!(l, "xq_cvt_f32_f16", g(mn), (256, 1, 1), 0, (&mut *yraw, part, mn as i64))?;
        xqlaunch!(l, "exl3_had_svh", (m as u32 * (q.n as u32 / 128), 1, 1), (32, 1, 1), 0, (&*yraw, &q.svh, &mut *y, q.n))?;
        Ok(false)
    }

    /// TP-B: the EP prefill combine — this rank's FP32 partial over its local picks (+ its shared
    /// term), one (chunked) all-reduce, one f16 rounding into psc.moe_out.
    pub(super) fn ep_combine_reduce_rows(&self, l: &Launcher, psc: &mut PrefillScratch, moe: &MoeLayer,
                                         ep: &EpShard, c: usize) -> Result<()> {
        let tp = self.tp.as_ref().context("an expert-parallel MoE layer without a TP attachment")?;
        anyhow::ensure!(ep.rank == tp.rank as usize && ep.world == tp.world as usize,
            "EP shard rank {}/{} != attached TP rank {}/{}", ep.rank, ep.world, tp.rank, tp.world);
        let h = self.cfg.hidden_size;
        let topk = self.cfg.num_experts_per_tok;
        let n = c * h;
        anyhow::ensure!(n <= tp.part.len(), "EP prefill combine: c={c} exceeds the partial buffer ({TP_MAX_ROWS} rows)");
        let part = tp.part_ptr();
        xqlaunch!(l, "xq_moe_combine_rows_ep", (c as u32, 1, 1), (1024, 1, 1), 4096,
                 (part, &psc.yd, &psc.ysh, &psc.cand, &psc.wts, &moe.sg, &psc.x,
                  topk as i32, h as i32, c as i32, (ep.shared_split || ep.rank == 0) as i32))?;
        // TP-F: the fp32 partial -> canonical sum -> moe_out (f16), the cvt pass fused into K2m
        let mo = *psc.moe_out.device_ptr() as u64;
        if let Some(sp) = psc.sp_rows {
            // TP-SP: the partial covers ALL rows (the router + EP experts ran on the gathered x); the
            // reduce-scatter gives this rank the canonical sum + one f16 rounding on its OWN rows of
            // moe_out (the all-reduce's values there), with the next inject+norm hooked on those rows.
            anyhow::ensure!(sp.c == c, "TP-SP: chunk {} vs MoE c {c}", sp.c);
            let io = crate::tp_xport::Io { src: part, src_f16: false, out: mo, out_f16: true, wire_f16: false };
            if let Some(hk) = psc.pf_hook.take() {
                anyhow::ensure!(hk.y == mo, "prefill overlap hook: y {:#x} is not moe_out {mo:#x}", hk.y);
                let mut f = |r0: usize, r1: usize| -> Result<()> { hk.inj_norm(l, r0, r1) };
                tp.sp_reduce_scatter(l, io, h, &sp, Some(crate::tp_xport::SpHook { min_rows: hk.rows, side: hk.dual, f: &mut f }))?;
                psc.pf_hooked = true;
                return Ok(());
            }
            return tp.sp_reduce_scatter(l, io, h, &sp, None);
        }
        if let Some(io) = tp.all_reduce_io(crate::tp_xport::Io { src: part, src_f16: false, out: mo, out_f16: true, wire_f16: false }, n)? {
            // TP-I2 item 1: the next hc_pre's inject+norm per landed row range (prefill_chunk set the
            // hook; psc.pf_hooked tells it the norm already ran)
            if let Some(hk) = psc.pf_hook.take() {
                anyhow::ensure!(hk.y == mo, "prefill overlap hook: y {:#x} is not moe_out {mo:#x}", hk.y);
                let mut f = |r0: usize, r1: usize| -> Result<()> { hk.inj_norm(l, r0, r1) };
                // TP-I3 (c1) fold: K2m + the inject+norm fused per whole-row epoch (moe_out is never written)
                let mut fk = |ctx: u64, lag: u32, r0: usize, r1: usize| -> Result<()> { hk.inj_norm_k2(l, ctx, lag, part, r0, r1) };
                let fold: Option<&mut dyn FnMut(u64, u32, usize, usize) -> Result<()>> =
                    if hk.fold && hk.hcn == 4 && h % 512 == 0 && h <= 4096 { Some(&mut fk) } else { None };
                tp.reduce_io_hooked(l, io, n, Some(crate::tp_xport::RowHook { row_len: h, min_rows: hk.rows, f: &mut f,
                                                                              side: hk.dual, fold }))?;
                psc.pf_hooked = true;
                return Ok(());
            }
            return tp.reduce_io(l, io, n);
        }
        tp.all_reduce_f32(l, part, n)?;
        xqlaunch!(l, "xq_cvt_f32_f16", ((n as u32).div_ceil(256), 1, 1), (256, 1, 1), 0,
                 (&mut psc.moe_out, part, n as i64))?;
        Ok(())
    }
}

