/// The TRUNK's per-rank geometry at world `w`: attention query heads / KV heads and GDN key /
/// value heads divided by W (every other field unchanged). The per-rank model IS a model with
/// fewer heads as far as every mixer kernel is concerned (GQA ratio 12 : 1 and GDN k : v = 1 : 3
/// are preserved), so kernels take the local counts unchanged. The MTP head stays replicated and
/// keeps the global `cfg` (T1 contract). Refuses a geometry that does not divide (boot fails).
pub(super) fn trunk_cfg(cfg: &crate::qwen::Config, w: usize) -> Result<crate::qwen::Config> {
    anyhow::ensure!(w >= 1, "trunk_cfg: world 0");
    let checks = [("num_heads", cfg.num_heads), ("num_kv_heads", cfg.num_kv_heads),
                  ("lin_num_k_heads", cfg.lin_num_k_heads), ("lin_num_v_heads", cfg.lin_num_v_heads)];
    for (what, v) in checks {
        anyhow::ensure!(v % w == 0 && v / w >= 1,
            "TP-B: {what} = {v} does not divide by world {w} — head-sharding needs whole heads per rank \
             (W=4 KV-pair replication is T3 work)");
    }
    anyhow::ensure!((cfg.num_heads / w) % (cfg.num_kv_heads / w) == 0 && (cfg.lin_num_v_heads / w) % (cfg.lin_num_k_heads / w) == 0,
        "TP-B: per-rank GQA / GDN k:v grouping broken at world {w}");
    let mut t = cfg.clone();
    t.num_heads /= w;
    t.num_kv_heads /= w;
    t.lin_num_k_heads /= w;
    t.lin_num_v_heads /= w;
    Ok(t)
}

/// Element ranges -> 16-block ranges, refusing any end that is not on a 128 boundary (a cut
/// H128 block is not exact — design §1.2, the G-T1-0 negative control).
pub(super) fn r16(v: &[(usize, usize)]) -> Result<Vec<(usize, usize)>> {
    v.iter().map(|&(a, b)| {
        anyhow::ensure!(a % 128 == 0 && b % 128 == 0 && b > a, "TP-B slice [{a}, {b}) is not 128-aligned");
        Ok((a / 16, b / 16))
    }).collect()
}

/// The per-rank ranges (element units) of each sharded trunk tensor class (design §1.3, the same
/// splits the G-T1-0 oracle proved exact at W=2).
pub(super) struct TrunkSplit {
    pub rank: usize,
    pub world: usize,
}

impl TrunkSplit {
    /// GDN in_proj_qkv columns = conv channels: [q nk*kd | k nk*kd | v nv*vd], contiguous k<->v
    /// head groups -> this rank's 1/W of each section (a load-time re-tile).
    pub fn gdn_qkv(&self, cfg: &crate::qwen::Config) -> Vec<(usize, usize)> {
        let (r, w) = (self.rank, self.world);
        let (nk, kd, nv, vd) = (cfg.lin_num_k_heads, cfg.lin_k_dim, cfg.lin_num_v_heads, cfg.lin_v_dim);
        let (qs, vs) = (nk * kd / w, nv * vd / w);
        vec![(r * qs, (r + 1) * qs), (nk * kd + r * qs, nk * kd + (r + 1) * qs),
             (2 * nk * kd + r * vs, 2 * nk * kd + (r + 1) * vs)]
    }
    /// GDN value-head range (in_proj_z cols, out_proj rows) in elements.
    pub fn gdn_v(&self, cfg: &crate::qwen::Config) -> (usize, usize) {
        let vs = cfg.lin_num_v_heads * cfg.lin_v_dim / self.world;
        (self.rank * vs, (self.rank + 1) * vs)
    }
    /// GDN value HEADS of this rank (a/b rows, A_log, dt_bias).
    pub fn gdn_heads(&self, cfg: &crate::qwen::Config) -> (usize, usize) {
        let n = cfg.lin_num_v_heads / self.world;
        (self.rank * n, (self.rank + 1) * n)
    }
    /// attention q_proj columns ([q | gate] per head, heads contiguous).
    pub fn attn_q(&self, cfg: &crate::qwen::Config) -> (usize, usize) {
        let s = cfg.num_heads / self.world * 2 * cfg.head_dim;
        (self.rank * s, (self.rank + 1) * s)
    }
    /// attention k/v columns (KV heads r*nkv/W ..; GQA: query head q reads KV head q / (nh/nkv)).
    pub fn attn_kv(&self, cfg: &crate::qwen::Config) -> (usize, usize) {
        let s = cfg.num_kv_heads / self.world * cfg.head_dim;
        (self.rank * s, (self.rank + 1) * s)
    }
    /// attention o_proj rows (the attention output of this rank's query heads).
    pub fn attn_o(&self, cfg: &crate::qwen::Config) -> (usize, usize) {
        let s = cfg.num_heads / self.world * cfg.head_dim;
        (self.rank * s, (self.rank + 1) * s)
    }
    /// shared expert intermediate (gate/up cols, down rows): the uneven 128-block deal (640 =
    /// 5 x 128 -> 384 | 256 at W=2), the split G-T1-0 proved.
    pub fn shared(&self, mi: usize) -> Result<(usize, usize)> {
        let (p, _) = split_128(mi, self.world).context("shared expert intermediate not 128-splittable")?;
        let (a, b) = p[self.rank][0];
        Ok((a * 16, b * 16))
    }
}

